import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createApp} from '../src/app.mjs';
import {listen} from './listen.mjs';
test('groups preserve enrollment, move atomically, protect default and retain exact run results',async t=>{
  const service=createApp({databasePath:':memory:',env:{ADMIN_USERNAME:'admin',ADMIN_PASSWORD:'isolated-password'}});
  const server=await listen(service.app);t.after(async()=>{server.closeAllConnections();await new Promise(resolve=>server.close(resolve));service.close();});
  const origin=`http://127.0.0.1:${server.address().port}`;let session={};
  const req=async(path,method='GET',body,headers={})=>{
    const response=await fetch(origin+'/api'+path,{method,headers:{Origin:origin,'Content-Type':'application/json',...session,...headers},...(body===undefined?{}:{body:JSON.stringify(body)})});
    return {status:response.status,data:await response.json(),headers:response.headers};
  };
  const login=await req('/auth/login','POST',{username:'admin',password:'isolated-password'});session={Cookie:login.headers.get('set-cookie').split(';')[0],'X-CSRF-Token':login.data.csrfToken};
  const enroll=async hostname=>{const token=await req('/enrollment-tokens','POST',{label:'test',maxUses:1,expiresInHours:1});return (await req('/agent/enroll','POST',{hostname,deviceId:hostname,enrollmentToken:token.data.token})).data;};
  const a=await enroll('GROUP-TEST-A'),b=await enroll('GROUP-TEST-B');
  assert.equal((await req('/groups')).data[0].endpointCount,2);
  assert.ok((await req('/endpoints')).data.every(ep=>ep.groupId==='new-endpoints'));
  const created=await req('/groups','POST',{name:'Cody',description:'Test fleet'});assert.equal(created.status,201);const id=created.data.id;
  assert.equal((await req('/groups','POST',{name:'cody'})).status,409);
  assert.equal((await req(`/groups/${id}/members`,'POST',{endpointIds:[a.endpointId,'missing']})).status,400);
  assert.equal((await req('/groups')).data.find(g=>g.id===id).endpointCount,0);
  assert.equal((await req(`/groups/${id}/members`,'POST',{endpointIds:[a.endpointId,b.endpointId,a.endpointId]})).data.moved,2);
  assert.equal((await req('/endpoints')).data[0].groupName,'Cody');
  const body={endpointIds:[a.endpointId,b.endpointId],kind:'powershell',payload:{script:'Write-Output test'},runName:'Cody · powershell',idempotencyKey:'group-run-one'};
  const run=await req('/jobs','POST',body);assert.equal(run.status,201);
  assert.equal((await req('/jobs','POST',body)).data.jobs[0].id,run.data.jobs[0].id);
  assert.equal((await req('/runs')).data.length,1);
  const agentHeaders={Authorization:`Bearer ${a.agentToken}`};
  const claim=(await req('/agent/jobs/claim','POST',{},agentHeaders)).data.job;
  await req(`/agent/jobs/${claim.id}/start`,'POST',{dispatchToken:claim.dispatchToken},agentHeaders);
  await req(`/agent/jobs/${claim.id}/output/0`,'PUT',{stream:'stdout',text:'group result complete'},agentHeaders);
  await req(`/agent/jobs/${claim.id}/complete`,'POST',{status:'succeeded',exitCode:0,summary:'done'},agentHeaders);
  assert.equal((await req(`/groups/${id}`,'PATCH',{name:'Staff',description:''})).data.name,'Staff');
  assert.equal((await req('/groups/new-endpoints','DELETE',{})).status,409);
  assert.equal((await req('/groups/new-endpoints','PATCH',{name:'Other'})).status,409);
  assert.equal((await req(`/groups/${id}`,'DELETE',{})).status,200);
  assert.ok((await req('/endpoints')).data.every(ep=>ep.groupId==='new-endpoints'));
  const saved=(await req(`/runs/${run.data.runId}`)).data;
  assert.equal(saved.name,'Cody · powershell');assert.equal(saved.jobs.length,2);assert.deepEqual(saved.endpointIds,[a.endpointId,b.endpointId]);
  assert.equal((await req('/runs')).data[0].counts.succeeded,1);
  assert.equal((await req(`/jobs/${claim.id}/output`)).data.chunks[0].text,'group result complete');
  assert.equal((await req('/agent/jobs/claim','POST',{},agentHeaders)).data.job,null);
  const tokenlessDevice='aaaaaaaa-bbbb-4ccc-8ddd-eeeeeeeeeeee';const join={hostname:'NEW-JOIN',deviceId:tokenlessDevice,joinSecret:'j'.repeat(40)};
  await req('/agent/join','POST',join);const pending=(await req('/join-requests')).data.find(row=>row.deviceId===tokenlessDevice);
  await req(`/join-requests/${pending.id}/approve`,'POST',{});const joined=(await req('/agent/join','POST',join)).data;
  assert.equal((await req(`/endpoints/${joined.endpointId}`)).data.groupId,'new-endpoints');
  await req('/users','POST',{username:'group-viewer',email:'',role:'viewer',password:'viewer-test-pass',currentPassword:'isolated-password'});
  const viewer=await req('/auth/login','POST',{username:'group-viewer',password:'viewer-test-pass'});session={Cookie:viewer.headers.get('set-cookie').split(';')[0],'X-CSRF-Token':viewer.data.csrfToken};
  assert.equal((await req('/groups')).status,200);assert.equal((await req('/runs')).status,200);
  assert.equal((await req('/groups','POST',{name:'forbidden'})).status,403);
  assert.equal((await req('/groups/new-endpoints/members','POST',{endpointIds:[a.endpointId]})).status,403);
});
